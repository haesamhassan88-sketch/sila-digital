function applyLang(lang){
  document.documentElement.lang=lang;
  document.body.dir=lang==="ar"?"rtl":"ltr";
  document.body.dataset.lang=lang;
  localStorage.setItem("sila-lang",lang);
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key=el.dataset.i18n;
    if(translations[lang][key]!==undefined) el.innerHTML=translations[lang][key];
  });
  document.querySelectorAll("[data-placeholder]").forEach(el=>{
    const key=el.dataset.placeholder;
    el.placeholder=translations[lang][key]||el.placeholder;
  });
}
const langBtn=document.querySelector("#langToggle");
if(langBtn){
  langBtn.addEventListener("click",()=>applyLang(document.body.dataset.lang==="ar"?"en":"ar"));
}
applyLang(localStorage.getItem("sila-lang")||"ar");

const menuBtn=document.querySelector(".menu-btn");
const navLinks=document.querySelector(".nav-links");
if(menuBtn&&navLinks){
  menuBtn.onclick=()=>navLinks.classList.toggle("open");
  navLinks.querySelectorAll("a").forEach(a=>a.onclick=()=>navLinks.classList.remove("open"));
}
document.querySelectorAll("[data-year]").forEach(el=>el.textContent=new Date().getFullYear());

